package io.github.umangtapania.logbus

import kotlin.concurrent.atomics.AtomicLong
import kotlin.concurrent.atomics.ExperimentalAtomicApi
import kotlin.uuid.ExperimentalUuidApi
import kotlin.uuid.Uuid
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.CoroutineExceptionHandler
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob

private const val DEFAULT_TAG = "LogBus"

/**
 * A fresh id for one run of the app: random characters with the start time appended, so two runs can
 * never collide even if they start in the same millisecond or the clock jumps backwards.
 */
@OptIn(ExperimentalUuidApi::class)
private fun newSessionId(): String = "${Uuid.random().toHexString().take(8)}-${nowMillis()}"

/**
 * The bus. You build one with routes (and optional interceptors), then log to it. Each log is stamped
 * with a [sessionId] and a sequence number, built into a [LogEvent], run through the central
 * interceptors, and handed to every route. [AsyncLogRoute]s are delivered on a background worker (the
 * calling thread never waits); [SyncLogRoute]s run inline on the calling thread, so their write
 * finishes before the log call returns.
 *
 * ```kotlin
 * val bus = LogBus(name = "main", routes = listOf(myRoute))
 * bus.d("hello")
 * ```
 *
 * The bus owns its coroutines. You choose *where* they run by passing a [dispatcher]; *when* they end
 * is [close]'s business and nobody else's. See [close] for exactly what shutting down does and doesn't
 * guarantee.
 *
 * @param name a label for this bus, used in diagnostics and configuration errors.
 * @param routes where logs go. With no routes the bus does nothing at all.
 * @param interceptors central interceptors, run once in order before any route sees the event.
 * @param dispatcher where async delivery runs. The default is fine for an app; pass a test dispatcher
 *   to make delivery deterministic in tests. Only a dispatcher, never a scope or a job — a route
 *   worker that could be cancelled from outside, or whose failure could cancel *your* coroutines,
 *   would make logging able to break the thing it is meant to report on.
 */
@OptIn(ExperimentalAtomicApi::class)
public class LogBus(
    /**
     * A label for this bus. It identifies the bus in diagnostics and in the messages it reports
     * configuration problems with, so give it something you'd recognise — `"main"`, `"analytics"`.
     * Required, because with more than one bus an unnamed failure tells you nothing.
     */
    public val name: String,
    private val routes: List<LogRoute>,
    private val interceptors: List<LogInterceptor> = emptyList(),
    dispatcher: CoroutineDispatcher = Dispatchers.Default,
) {
    /**
     * Identifies this run of the app. Generated by the bus — never supplied, because a value a caller
     * chose could repeat, and the whole point is that it can't. Every [LogEvent] the bus produces
     * carries it, so logs from different runs never collide even though [LogEvent.sequence] restarts
     * at 1 each time.
     */
    public val sessionId: String = newSessionId()

    // Routes split by delivery model, partitioned once up front. Async routes each get their own worker
    // (mailbox + single consumer coroutine); sync routes run inline in deliver(). Both lists are empty
    // when there are no routes, so the "no routes → do nothing" rule still holds.
    private val syncRoutes: List<SyncLogRoute> = routes.filterIsInstance<SyncLogRoute>()
    // The cheapest filter there is: the lowest level any route could want, worked out once. Anything
    // below it is dropped before an event is even allocated — no LogEvent, no nowMillis(), no
    // interceptors, no mailbox. With no routes there is no floor to clear, so nothing gets through.
    private val minPriority: Int = routes.minOfOrNull { it.minPriority } ?: Int.MAX_VALUE

    // Stamps every delivered event with its position in this session. Assigned at construction rather
    // than after the interceptors, because the event is built before they run — an interceptor that
    // drops a log therefore burns a number, which is harmless: every route sees the same stream, so
    // comparing routes against each other still lines up exactly.
    private val sequencer = AtomicLong(0L)

    // Durable routes are recognised and contribute their level floor, but nothing is delivered to them
    // yet — they are fed from the log store, which isn't built. Wiring them up is the next piece.
    private val durableRoutes: List<DurableLogRoute> = routes.filterIsInstance<DurableLogRoute>()

    init {
        require(name.isNotBlank()) {
            "LogBus was created with a blank name. The name identifies this bus in diagnostics and " +
                "in configuration errors like this one, which matters as soon as there is more than " +
                "one bus. Fix: pass one, e.g. LogBus(name = \"main\", routes = listOf(...))."
        }

        val shared = durableRoutes.groupBy { it.id }.filterValues { it.size > 1 }
        require(shared.isEmpty()) {
            val clashes = shared.entries.joinToString("; ") { (id, routes) ->
                val names = routes.joinToString(" and ") { it::class.simpleName ?: "<unnamed route>" }
                "id \"$id\" is used by $names"
            }
            "LogBus '$name': every durable route needs its own id, but $clashes. An id keys that " +
                "route's delivery cursor in the log store, so routes sharing one would each receive " +
                "only the logs the other had not already taken — each silently missing about half. " +
                "Fix: give each route a different id."
        }
    }

    // Everything below is built after the init block, so a configuration it rejects creates no job, no
    // scope and no coroutines.

    // The bus's own job, never the caller's. SupervisorJob so one worker's failure can't reach the
    // others, and because it is a CompletableJob, close() can say "no new work, finish what you have"
    // instead of cancelling. The handler is the last line of defence: under a supervisor an uncaught
    // exception still travels to the platform's default handler, which on Android kills the process —
    // a bug in logging must never do that.
    private val job = SupervisorJob()
    private val scope = CoroutineScope(
        job + dispatcher + CoroutineExceptionHandler { _, _ -> },
    )
    private val workers: List<RouteWorker> =
        routes.filterIsInstance<AsyncLogRoute>().map { RouteWorker(it, scope) }

    // Open/closed and "how many log() calls are inside right now", in one number — because the two have
    // to be read together. Checking a separate flag and a separate counter leaves a window where a log
    // passes the flag, close() sees the counter at zero and shuts the mailboxes, and that log is then
    // delivered to nothing.
    //
    //   >= 0  open; the value is the number of log() calls between the gate and the hand-off.
    //   <  0  closed; the sign bit is set and the rest is still that count.
    //
    // Whoever takes the count to "closed and empty" finishes the shutdown — close() itself if no log
    // was in flight, otherwise the last log on its way out. So nothing waits and nothing is lost.
    private val gate = AtomicLong(0L)

    /** Log at any level — including custom ones: `bus.log(Analytics, "checkout done")`. */
    public fun log(level: LogLevel, message: String, tag: String? = null, error: Throwable? = null) {
        // No routes, or below every route's floor → do nothing, and don't build the event. These come
        // first so the common "nobody wants this level" case stays one comparison, with no atomic.
        if (routes.isEmpty() || level.priority < minPriority) return
        if (!enter()) return // closed: refuse, and build nothing
        try {
            var event = LogEvent(
                sessionId = sessionId,
                sequence = sequencer.addAndFetch(1L),
                level = level,
                tag = tag ?: DEFAULT_TAG,
                message = message,
                error = error?.let { LogError.Live(it) },
                timeMillis = nowMillis(),
            )
            for (interceptor in interceptors) {
                event = interceptor.intercept(event) ?: return // null → drop the log
            }
            deliver(event)
        } catch (_: Throwable) {
            // Never crash the caller. A misbehaving interceptor stays contained here.
        } finally {
            // Must always run. An interceptor that throws, or one that drops the log with a `return`,
            // would otherwise leave the count raised for good and the shutdown would never finish.
            exit()
        }
    }

    public fun v(message: String, tag: String? = null): Unit = log(DefaultLevel.VERBOSE, message, tag)
    public fun d(message: String, tag: String? = null): Unit = log(DefaultLevel.DEBUG, message, tag)
    public fun i(message: String, tag: String? = null): Unit = log(DefaultLevel.INFO, message, tag)
    public fun w(message: String, tag: String? = null): Unit = log(DefaultLevel.WARNING, message, tag)
    public fun e(message: String, tag: String? = null, error: Throwable? = null): Unit =
        log(DefaultLevel.ERROR, message, tag, error)

    /**
     * Hands the event to each route. Async routes get it via their mailbox — instant, never blocks;
     * each worker drains in order, so logs stay linear per route and a slow route can't hold up the
     * others. A route whose own [LogRoute.minPriority] this event doesn't clear isn't queued at all, so
     * its mailbox only ever holds logs it actually wants. Sync routes run inline here on the calling
     * thread, each in its own try/catch so one broken sync route can't crash the caller or stop the
     * remaining routes.
     */
    private fun deliver(event: LogEvent<LogError.Live>) {
        for (route in syncRoutes) {        // sync: inline on the caller's thread
            try {
                route.log(event)
            } catch (cause: Throwable) {
                // Contain a misbehaving sync route: the caller never sees it, and the other routes still
                // run — but tell the route its event is gone rather than dropping it in silence.
                route.reportDropped(event, cause)
            }
        }
        workers.forEach { it.send(event) } // async: instant enqueue, never blocks
    }

    /**
     * Stop the bus. It stops accepting new logs at once; everything already accepted is still
     * delivered. This returns immediately — it never waits and never cancels, so whatever is queued in
     * the async workers keeps draining in the background until it is gone, and the bus's scope then
     * ends by itself.
     *
     * A log call already underway — event built, interceptors running, not yet handed to the routes —
     * counts as accepted and will be delivered. A log that arrives afterwards is refused; it was never
     * accepted, so it is not reported through [LogRoute.onDropped].
     *
     * Safe to call more than once, and from anywhere: it doesn't suspend, so `onDestroy`, a shutdown
     * hook or a `finally` can all call it.
     *
     * What it does **not** promise is that the queued logs arrive before the process dies. Nothing
     * could: an [AsyncLogRoute]'s mailbox lives in memory, and most of the ways a process ends — a
     * native crash, an out-of-memory kill, the user swiping the app away — run no code at all. For
     * logs that have to survive that, use a [DurableLogRoute]: those are on disk before the route ever
     * sees them.
     */
    public fun close() {
        while (true) {
            val current = gate.load()
            if (current < 0L) return // already closed
            if (gate.compareAndSet(current, current or Long.MIN_VALUE)) {
                // Exactly one path sees the transition to "closed and empty", so finishClose() runs
                // once: here when nothing was in flight, otherwise in the last log call's exit().
                if (current == 0L) finishClose()
                return
            }
        }
    }

    /**
     * Wait for the async workers to finish draining. Only meaningful after [close] — nothing ends a
     * worker until its mailbox is closed, so calling this on an open bus waits forever.
     *
     * Internal, for tests. The published API has no `flush`/`await` on purpose: on a logger it reads as
     * a promise that the logs are now safe, and [close] explains why no such promise can be made.
     */
    internal suspend fun join() {
        job.join()
    }

    /**
     * Take the last step of the shutdown: stop the mailboxes taking new events (what is already queued
     * still drains), then mark the job complete so it finishes on its own once the workers end. Called
     * once, by whoever took the gate to "closed and empty".
     */
    private fun finishClose() {
        workers.forEach { it.close() }
        job.complete()
    }

    /**
     * Claim a place in the in-flight count, or find the bus closed. Taking the place first and backing
     * out second is what makes this a single atomic step: a log that gets in is guaranteed to be
     * delivered, and a log that doesn't never existed.
     */
    private fun enter(): Boolean {
        if (gate.addAndFetch(1L) >= 0L) return true
        // Refused. Back out with a plain decrement, never through exit(): a log that was turned away
        // can't be the last one out, because if the bus were already empty the shutdown had finished.
        gate.addAndFetch(-1L)
        return false
    }

    /** Give up the place. The caller that empties a closed bus finishes the shutdown. */
    private fun exit() {
        if (gate.addAndFetch(-1L) == Long.MIN_VALUE) finishClose()
    }
}
